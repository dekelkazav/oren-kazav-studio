// Converts original photos into web-ready images.
//
//   npm run images                    work photos + catalog albums
//   npm run images -- "path/to/dir"   only the photos in that folder, as work photos
//
// Work photos: every image in חומרים/תמונות becomes images/works/<name>.webp (1400px)
// and <name>-sm.webp (700px). Products and the gallery use them by name (image: "<name>").
//
// Catalog albums: every product in data.js with a `folder` gets the photos of
// חומרים/<folder>, in file-name order, as images/catalog/<id>/01.webp (1400px),
// 01-sm.webp (700px) and 01-xs.webp (240px thumbnails). The number of photos per
// product is written to catalog-images.js, which the site reads.
import sharp from "sharp";
import vm from "node:vm";
import { readdir, mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join, parse } from "node:path";

const MATERIALS = "חומרים";
const WORKS_FOLDER = "תמונות";
const IMAGE = /\.(jpe?g|png|webp|heic|tiff?)$/i;

const listImages = async (dir) => (await readdir(dir)).filter((f) => IMAGE.test(f)).sort();

async function convert(file, dest, sizes) {
  const input = sharp(file).rotate();
  for (const [suffix, size, quality] of sizes) {
    const out = `${dest}${suffix}.webp`;
    const info = await input.clone()
      .resize({ width: size, height: size, fit: "inside", withoutEnlargement: true })
      .webp({ quality })
      .toFile(out);
    console.log(`${out}  ${info.width}x${info.height}  ${Math.round(info.size / 1024)}KB`);
  }
}

async function workPhotos(src) {
  const out = join("images", "works");
  await mkdir(out, { recursive: true });
  const files = await listImages(src);
  if (!files.length) console.log(`No images found in "${src}"`);
  for (const file of files) {
    const name = parse(file).name.trim().replace(/\s+/g, "-").toLowerCase();
    await convert(join(src, file), join(out, name), [["", 1400, 80], ["-sm", 700, 78]]);
  }
}

async function catalogAlbums() {
  // data.js is a browser script, so run it in a sandbox to read PRODUCTS
  const sandbox = {};
  vm.runInNewContext(`${await readFile("data.js", "utf8")}\n;globalThis.PRODUCTS = PRODUCTS;`, sandbox);
  const albums = sandbox.PRODUCTS.filter((p) => p.folder);

  const counts = {};
  for (const p of albums) {
    const src = join(MATERIALS, p.folder);
    if (!existsSync(src)) { console.warn(`! Folder "${src}" (product "${p.id}") does not exist`); continue; }
    const out = join("images", "catalog", p.id);
    await mkdir(out, { recursive: true });
    const files = await listImages(src);
    for (const [i, file] of files.entries()) {
      const dest = join(out, String(i + 1).padStart(2, "0"));
      await convert(join(src, file), dest, [["", 1400, 80], ["-sm", 700, 78], ["-xs", 240, 72]]);
    }
    counts[p.id] = files.length;
  }

  // a folder in חומרים that no product points to is probably a new album
  const linked = new Set(albums.map((p) => p.folder));
  for (const d of await readdir(MATERIALS, { withFileTypes: true })) {
    if (d.isDirectory() && d.name !== WORKS_FOLDER && !linked.has(d.name)) {
      console.warn(`! Folder "${join(MATERIALS, d.name)}" is not used by any product (add folder: "${d.name}" in data.js)`);
    }
  }

  await writeFile("catalog-images.js",
    "// Generated by `npm run images` – do not edit by hand.\n" +
    "// Number of photos in each catalog product's album (images/catalog/<id>/).\n" +
    `window.CATALOG_IMAGES = ${JSON.stringify(counts, null, 2)};\n`);
  console.log("catalog-images.js:", counts);
}

if (process.argv[2]) {
  await workPhotos(process.argv[2]);
} else {
  await workPhotos(join(MATERIALS, WORKS_FOLDER));
  await catalogAlbums();
}
